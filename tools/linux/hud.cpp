// The HUD distance extension (the Windows launcher's HUD distance mod, tools/launcher/hud_mod.hpp):
// built from the player's own game files, it moves X4's cockpit HUD a factor farther away and scales
// it up by the same factor, so it keeps its apparent size at a more comfortable depth in VR. Put in
// place for VR, moved aside for 2D.

